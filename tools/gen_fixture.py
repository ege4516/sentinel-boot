"""Generate the C header with test fixtures for the QEMU self-test firmware.

Fresh root and device keys are generated on every run and exist only inside
the generated header (in the build directory). They are test keys: nothing
secret is committed to the repository.

Images follow a simple byte pattern that the firmware can recompute, so the
plaintext does not need to be embedded:  byte(i) = ((i * 2654435761) >> 24) ^ seed
"""
import importlib.util
import sys
import tempfile
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric import ec

import sentinel_log

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
spec = importlib.util.spec_from_file_location("sentinel_sign", HERE / "sentinel_sign.py")
signer = importlib.util.module_from_spec(spec)
spec.loader.exec_module(signer)


def pattern(size, seed):
    return bytes((((i * 2654435761) & 0xFFFFFFFF) >> 24) ^ seed for i in range(size))


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    return "static const uint8_t %s[%d] = {\n%s\n};\n" % (name, len(data), "\n".join(lines))


def main():
    out = Path(sys.argv[1])
    root = ec.generate_private_key(ec.SECP256R1())
    log_key = ec.generate_private_key(ec.SECP256R1())
    attacker = ec.generate_private_key(ec.SECP256R1())
    device = ec.generate_private_key(ec.SECP256R1())
    dev_pub = signer.pub_bytes(device.public_key())
    dev_priv = device.private_numbers().private_value.to_bytes(32, "big")

    log = sentinel_log.Log(tempfile.mkdtemp(prefix="sb-fixture-log-"))

    def pkg(key, version, counter, size, seed, logged=True, proof=None):
        # Releases are logged in the order they are built: v1, v2, v3.
        return signer.build_package(key, dev_pub, pattern(size, seed),
                                    signer.parse_version(version), counter,
                                    log=log if logged else None, log_key=log_key,
                                    proof_override=proof)

    v1 = pkg(root, "1.0.0", 1, 3000, 0x11)
    v2 = pkg(root, "2.0.0", 2, 5000, 0x22)
    v3 = pkg(root, "2.1.0", 3, 2500, 0x33)
    # Signed with the REAL root key but never logged: the proof block is copied from v2.
    unlogged = pkg(root, "7.0.0", 7, 2500, 0x55, logged=False,
                   proof=v2[signer.MANIFEST_LEN:signer.HEADER_LEN])
    # Signed with the attacker's own root key; the attacker has no log key either.
    evil = pkg(attacker, "9.9.9", 9, 2500, 0x44, logged=False,
               proof=v2[signer.MANIFEST_LEN:signer.HEADER_LEN])

    parts = [
        "/* Generated by tools/gen_fixture.py. TEST KEYS ONLY. Do not edit or commit. */\n",
        "#include <stdint.h>\n",
        c_array("FX_ROOT_PUB", signer.pub_bytes(root.public_key())),
        c_array("FX_DEVICE_PRIV", dev_priv),
        c_array("FX_LOG_PUB", signer.pub_bytes(log_key.public_key())),
        c_array("FX_PKG_V1", v1),
        c_array("FX_PKG_V2", v2),
        c_array("FX_PKG_V3", v3),
        c_array("FX_PKG_UNLOGGED", unlogged),
        c_array("FX_PKG_EVIL", evil),
    ]
    out.write_text("\n".join(parts), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
