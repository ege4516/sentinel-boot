"""Generate Merkle inclusion-proof test vectors for tests/vectors/.

The tree and the proofs come from the recursive definitions in RFC 9162
section 2.1 (tools/sentinel_log.py), i.e. not from the verification algorithm
the C code implements. Leaf i of every tree holds the bytes b"leaf-<i>".

Usage: gen_merkle_vectors.py <output.inc>
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import sentinel_log as sl  # noqa: E402

FULL = range(1, 25)                       # every leaf of every tree up to 24 leaves
SAMPLED = [31, 32, 33, 63, 64, 65, 100, 127, 128, 129, 200, 255, 256]


def leaves(n):
    return [b"leaf-%d" % i for i in range(n)]


def main():
    rows = []
    for n in list(FULL) + SAMPLED:
        data = leaves(n)
        root = sl.mth(data).hex()
        if n in FULL:
            idx = range(n)
        else:
            idx = sorted({0, 1, 2, n // 3, n // 2, n - 2, n - 1})
        for i in idx:
            p = b"".join(sl.path(i, data)).hex()
            rows.append('{%d, %d, "%s", "%s"},' % (n, i, root, p))
    header = ("// Generated by tools/gen_merkle_vectors.py from the RFC 9162 2.1 definitions.\n"
              "// Fields: tree size, leaf index, root hash, inclusion path (hex).\n"
              "// Leaf i is the byte string \"leaf-<i>\". Do not edit by hand.\n")
    Path(sys.argv[1]).write_text(header + "\n".join(rows) + "\n", encoding="utf-8", newline="\n")
    print("%d vectors" % len(rows))


if __name__ == "__main__":
    main()
